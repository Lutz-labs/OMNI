package dev.omalauncher.backend

/**
 * Generates the backend's chroot entry script — the one file that knows the
 * mount sequence and the chroot invocation. It mirrors the user's own
 * `~/chroot-kali` (mounts are guarded against what is already mounted, hosts
 * are synced, then the guest is entered), but with three modes:
 *
 * - `--mount-only`: mounts anything missing and exits — used at prepare()
 *   time so the whole mount lifecycle has a single point of control.
 * - `shell`: mounts, then execs a persistent non-login bash in the guest,
 *   the long-lived channel pooled shells and streams run through.
 * - `-c <cmd>`: mounts, then runs one command and exits — one-shot runs.
 *
 * SECURITY NOTE — this script is NOT an isolation boundary. `env -i` only
 * clears environment variables. What a process in the guest can reach is
 * decided by the kernel, exactly as for any other root process:
 * - mounts: only the bound /dev, /dev/pts, /proc, /sys and the rootfs tree are
 *   visible; Android's /data, /system etc. are not mounted inside.
 * - UID/capabilities: the guest runs as uid 0 with whatever capabilities the
 *   escalator (KernelSU su) grants — a full Linux root *inside this tree*,
 *   not Android root over the host.
 * - SELinux: the process keeps Android's SELinux domain from the escalator;
 *   chroot does not change it, and host-side denials still apply.
 * The entry script must never be treated as a sandbox.
 */
object EntryScript {

    fun build(config: ChrootConfig): String {
        val rootfs = shellQuote(config.rootfs)
        val t = config.hostTools
        val mount = shellQuote(t.mount)
        val chroot = shellQuote(t.chroot)
        val cat = shellQuote(t.cat)
        val hosts = shellQuote(config.hostsSource)
        val guestEnv =
            listOf(
                "HOME=" + config.guestHome,
                "USER=root",
                "LOGNAME=root",
                "SHELL=/bin/bash",
                "TERM=xterm-256color",
                "LANG=C.UTF-8",
                "PATH=" + config.guestPath,
            ).joinToString(" ")
        val bash = shellQuote("/bin/bash")
        return """
            |#!/bin/bash
            |# Generated by OMNI (EntryScript.kt). Do not edit: rewritten at every prepare().
            |set -eu
            |ROOT=$rootfs
            |M=$mount
            |C=$chroot
            |CAT=$cat
            |
            |has() { grep -Fq " ${'$'}ROOT${'$'}1 " /proc/mounts 2>/dev/null; }
            |
            |"${'$'}M" --bind /dev "${'$'}ROOT/dev"          && echo "mounted ${'$'}ROOT/dev"          || has /dev
            |"${'$'}M" --bind /dev/pts "${'$'}ROOT/dev/pts"  && echo "mounted ${'$'}ROOT/dev/pts"  || has /dev/pts
            |"${'$'}M" -t proc proc "${'$'}ROOT/proc"        && echo "mounted ${'$'}ROOT/proc"        || has /proc
            |"${'$'}M" --bind /sys "${'$'}ROOT/sys"          && echo "mounted ${'$'}ROOT/sys"          || has /sys
            |
            |"${'$'}CAT" $hosts > "${'$'}ROOT/etc/hosts"
            |
            |mode=${'$'}{1:--mount-only}
            |if [ "${'$'}mode" = --mount-only ]; then exit 0; fi
            |
            |if [ "${'$'}mode" = shell ]; then
            |  exec "${'$'}C" "${'$'}ROOT" /usr/bin/env -i $guestEnv $bash --noprofile --norc
            |fi
            |
            |shift
            |exec "${'$'}C" "${'$'}ROOT" /usr/bin/env -i $guestEnv $bash --noprofile --norc -c "${'$'}@"
        """.trimMargin()
    }
}
